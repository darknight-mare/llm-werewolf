def assign_personas():
    """Give the five AI seats distinct personalities for the whole game."""
    return [None] + [dict(persona) for persona in random.sample(PERSONAS, 5)]


def ensure_personas(game):
    """Add personalities to games created before this feature was available."""
    if "personas" not in game:
        game["personas"] = assign_personas()
    return game["personas"]


def public_persona(game, seat):
    """Expose social preferences without any role or private game knowledge."""
    if seat == 0:
        return {"label": "真人玩家", "description": "由你决定自己的发言与选择"}
    persona = ensure_personas(game)[seat]
    return {
        "label": persona["label"],
        "description": persona["priorities"] + "。" + persona["speaking_style"] + "。",
    }
